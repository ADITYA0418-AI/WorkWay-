const LanguageContext = createContext(null);

export const LanguageProvider = ({ children }) => {
  const [currentLang, setCurrentLang] = useState(() => {
    return localStorage.getItem('workway_lang') || 'en';
  });
  const [timeFormat, setTimeFormat] = useState(() => {
    return localStorage.getItem('workway_time_format') || '12h';
  });
  const [currency, setCurrency] = useState(() => {
    return localStorage.getItem('workway_currency') || 'INR';
  });

  const selectedLangObj = LANGUAGES.find(l => l.code === currentLang) || LANGUAGES[0];
  const isRTL = selectedLangObj.dir === 'rtl';

  // Apply RTL/LTR to document element
  useEffect(() => {
    document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
    document.documentElement.lang = currentLang;
    localStorage.setItem('workway_lang', currentLang);
  }, [currentLang, isRTL]);

  useEffect(() => {
    localStorage.setItem('workway_time_format', timeFormat);
  }, [timeFormat]);

  useEffect(() => {
    localStorage.setItem('workway_currency', currency);
  }, [currency]);

  const setLanguage = (langCode) => {
    if (TRANSLATIONS[langCode]) {
      setCurrentLang(langCode);
    }
  };

  const t = (key, fallback = '') => {
    const langDict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    const enDict = TRANSLATIONS.en;
    return enDict[key] || fallback || key;
  };

  return (
    <LanguageContext.Provider value={{
      currentLang,
      setLanguage,
      setCurrentLang: setLanguage,
      timeFormat,
      setTimeFormat,
      currency,
      setCurrency,
      isRTL,
      selectedLang: selectedLangObj,
      languages: LANGUAGES,
      t
    }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
